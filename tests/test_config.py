import unittest
import tempfile
import configparser
from pathlib import Path

import martpy
from martpy.utils.config import Configuration, get_lang, set_lang
from martpy.inputs._io_utils import _build_header


class TestConfiguration(unittest.TestCase):

    def setUp(self):
        # Save original config to restore later
        self.original_config_file = martpy.utils.config.CONFIG_FILE
        self.original_config_dir = martpy.utils.config.CONFIG_DIR

        # Use a temporary config file
        self.tmp_dir = tempfile.TemporaryDirectory()
        self.tmp_path = Path(self.tmp_dir.name)

        martpy.utils.config.CONFIG_DIR = self.tmp_path
        martpy.utils.config.CONFIG_FILE = self.tmp_path / "config.ini"

        # Reset singleton to force reload
        Configuration._instance = None

    def tearDown(self):
        # Restore original config
        martpy.utils.config.CONFIG_DIR = self.original_config_dir
        martpy.utils.config.CONFIG_FILE = self.original_config_file
        Configuration._instance = None
        self.tmp_dir.cleanup()

    def test_default_lang(self):
        # Default should be 'fr'
        self.assertEqual(get_lang(), 'fr')

    def test_set_lang(self):
        set_lang('en')
        self.assertEqual(get_lang(), 'en')

        # Verify persistence
        config = configparser.ConfigParser()
        config.read(martpy.utils.config.CONFIG_FILE)
        self.assertEqual(config.get('general', 'lang'), 'en')

        # Reset singleton and check it reloads correctly
        Configuration._instance = None
        self.assertEqual(get_lang(), 'en')

    def test_io_utils_header(self):
        # FR
        set_lang('fr')
        header_fr = _build_header('Tit')
        self.assertIn('Fin du texte libre', header_fr[1])

        # EN
        set_lang('en')
        header_en = _build_header('Tit')
        self.assertIn('End of Header lines', header_en[1])


if __name__ == '__main__':
    unittest.main()
